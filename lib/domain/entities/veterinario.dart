class Veterinario {
  final int id;
  final String nombre;
  final String especialidad;
  final String telefono;
  final String email;
  final String horarioAtencion;

  const Veterinario({
    required this.id,
    required this.nombre,
    required this.especialidad,
    required this.telefono,
    required this.email,
    required this.horarioAtencion,
  });
}
